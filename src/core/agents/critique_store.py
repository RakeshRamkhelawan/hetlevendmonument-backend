"""Thread-safe storage for agent critiques with tenant isolation.

This module provides persistent storage for critiques generated by the CriticAgent,
with support for tenant isolation, aggregation, and querying for the FeedbackLoopAgent.
"""

import logging
import threading
from collections import defaultdict
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from typing import Any, Optional, TypedDict

logger = logging.getLogger(__name__)


@dataclass
class Critique:
    """A single critique entry for an agent's task execution."""

    critique_id: str
    agent_name: str
    task_id: str
    tenant_id: int
    score: float  # 0.0 - 1.0
    issues: list[str]
    suggestions: list[str]
    mode: str  # ADVISORY, BLOCKING, SILENT
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    metadata: dict[str, Any] = field(  # TODO(TYPE): replace Any with concrete type
        default_factory=dict
    )  # TODO(TYPE): replace Any with concrete type


class CritiqueTimeseriesStats(TypedDict):
    hour: str
    agent_name: str
    avg_score: float
    critique_count: int


class CritiqueStore:
    """
    Thread-safe in-memory store for critiques with tenant isolation.

    This is a singleton class that maintains critiques across all agents
    and provides aggregation helpers for the FeedbackLoopAgent.
    """

    _instance: Optional["CritiqueStore"] = None
    # `threading.Lock`, niet `asyncio.Lock` (ADR-036 OP-16). CritiqueStore is een
    # procesbrede singleton, bereikt via CriticMixin -> EnhancedBaseAgent tijdens
    # agent-uitvoering; dramatiq draait actors met meerdere workerthreads
    # (docker-compose.yml: workflow-worker --threads 4, learning-worker --threads 2),
    # elk met zijn EIGEN event loop. `asyncio.Lock` geeft dan geen wederzijdse
    # uitsluiting: de tweede loop hangt voor altijd op de acquire (gemeten, niet
    # aangenomen -- zie tests/unit/agents/test_critique_store_cross_thread_lock.py).
    # `threading.Lock` heeft dat probleem niet en mag daarom wel gewoon eager hier
    # staan; geen van de kritieke secties hieronder bevat een `await`, dus een korte
    # synchrone acquire binnen een `async def`-methode blokkeert de loop niet
    # langer dan de in-memory dict-mutatie zelf kost.
    _lock: threading.Lock = threading.Lock()
    _initialized: bool = False
    _HITL_SCORE_THRESHOLD: float = 0.40

    def __new__(cls) -> "CritiqueStore":
        if cls._instance is None:
            cls._instance = super().__new__(cls)
            cls._instance._initialized = False
        return cls._instance

    def __init__(self) -> None:
        if self._initialized:
            return

        self._initialized = True
        self._critiques: dict[int, list[Critique]] = defaultdict(list)
        self._critiques_by_agent: dict[int, dict[str, list[Critique]]] = defaultdict(
            lambda: defaultdict(list)
        )
        self._critiques_by_task: dict[int, dict[str, Critique]] = defaultdict(dict)
        self._max_critiques_per_tenant = 10000  # Limit to prevent memory issues
        self._last_mv_refresh: datetime | None = None
        self._mv_refresh_cooldown_s: int = 300  # 5 min

    async def store(self, critique: Critique) -> bool:
        """
        Store a critique with tenant isolation.

        Args:
            critique: The critique to store

        Returns:
            True if stored successfully
        """
        with self._lock:
            tenant_id = critique.tenant_id

            # Enforce storage limit per tenant (FIFO)
            if len(self._critiques[tenant_id]) >= self._max_critiques_per_tenant:
                removed = self._critiques[tenant_id].pop(0)
                # Also remove from agent index
                agent_critiques = self._critiques_by_agent[tenant_id][removed.agent_name]
                if removed in agent_critiques:
                    agent_critiques.remove(removed)

            # Store in main list
            self._critiques[tenant_id].append(critique)

            # Index by agent
            self._critiques_by_agent[tenant_id][critique.agent_name].append(critique)

            # Index by task (overwrites if task already exists)
            self._critiques_by_task[tenant_id][critique.task_id] = critique

            logger.debug(
                f"Stored critique {critique.critique_id} for {critique.agent_name}",
                extra={
                    "agent_name": critique.agent_name,
                    "task_id": critique.task_id,
                    "tenant_id": tenant_id,
                    "score": critique.score,
                },
            )

        # DB write outside the lock -- lock only protects in-memory structures (SP-AGT-005)
        # Wrap in try/except: _persist_to_db already catches, but test doubles bypass it.
        try:
            await self._persist_to_db(critique)
        except Exception as e:
            logger.error(
                "critique store db write failed: %s: %s", type(e).__name__, e, exc_info=True
            )

        # Materialized view refresh guard: atomic decision within _lock, refresh outside.
        # FA-002: read+write _last_mv_refresh atomically to prevent concurrent double-refresh.
        should_refresh = False
        with self._lock:
            now = datetime.now(timezone.utc)
            if (
                self._last_mv_refresh is None
                or (now - self._last_mv_refresh).total_seconds() > self._mv_refresh_cooldown_s
            ):
                should_refresh = True
                self._last_mv_refresh = now  # mark before releasing lock

        if should_refresh:
            await self._refresh_mv()

        if critique.score < self._HITL_SCORE_THRESHOLD:
            try:
                await self._create_hitl_ticket(critique)
            except Exception as e:
                logger.error(
                    "critique hitl escalation failed: %s: %s", type(e).__name__, e, exc_info=True
                )

        return True

    async def _create_hitl_ticket(self, critique: Critique) -> None:
        """Create a HITL ticket for low-scoring critiques (score < _HITL_SCORE_THRESHOLD).

        SILENT mode is intentionally excluded: it is telemetry-only and must not block pipelines.
        Lazy imports avoid circular dep at module load time (agents -> tool_broker.hitl_repository).
        ignore: agents -> src.core.tool_broker.hitl_repository (Cat B, SP-AGT-007, see .importlinter)
        ignore: agents -> src.core.database.database (Cat B, SP-AGT-006, see .importlinter)
        ignore: agents -> src.core.utils.best_effort (Cat B, SP-AGT-006, see .importlinter)
        """
        if critique.mode.lower() == "silent":
            return
        try:
            from src.core.database.database import db_manager  # noqa: PLC0415
            from src.core.tool_broker.hitl_repository import (  # noqa: PLC0415
                HITLTicketRepository,
                generate_ticket_ref,
            )
            from src.core.utils.best_effort import best_effort  # noqa: PLC0415

            await db_manager.initialize()
            async with best_effort("critique_hitl_ticket_creation"):
                async with db_manager.get_session() as db:
                    repo = HITLTicketRepository(db)
                    await repo.create(
                        ticket_ref=generate_ticket_ref(),
                        tenant_id=critique.tenant_id,
                        tool_name="critic_agent",
                        payload={
                            "agent_name": critique.agent_name,
                            "task_id": critique.task_id,
                            "score": critique.score,
                            "reason": "low_critique_score",
                        },
                        risk_level="HIGH",
                    )
                    await db.commit()
        except Exception as e:
            logger.error(
                "critique hitl ticket creation failed: %s: %s", type(e).__name__, e, exc_info=True
            )

    async def _refresh_mv(self) -> None:
        """Refresh critique_hourly_stats materialized view (best-effort, non-blocking).

        ignore: agents -> src.core.database.database (Cat B, SP-AGT-006, see .importlinter)
        ignore: agents -> src.core.utils.best_effort (Cat B, SP-AGT-006, see .importlinter)
        """
        try:
            from src.core.database.database import db_manager  # noqa: PLC0415
            from src.core.utils.best_effort import best_effort  # noqa: PLC0415
            from sqlalchemy import text  # noqa: PLC0415

            await db_manager.initialize()
            async with best_effort("critique_hourly_stats mv refresh"):
                async with db_manager.get_session() as db:
                    await db.execute(
                        text("REFRESH MATERIALIZED VIEW CONCURRENTLY critique_hourly_stats")
                    )
                    await db.commit()
        except Exception as e:
            logger.error("critique mv refresh failed: %s: %s", type(e).__name__, e, exc_info=True)

    async def _persist_to_db(self, critique: Critique) -> None:
        """Secondary write to PostgreSQL (best-effort -- DB failures never break in-memory store).

        Lazy imports avoid circular dep at module load time (agents -> database).
        Called outside the asyncio.Lock to prevent lock contention during DB retries.
        ignore: agents -> src.core.database.database (Cat B, SP-AGT-005, see .importlinter)
        ignore: agents -> src.core.utils.best_effort (Cat B, SP-AGT-006, see .importlinter)
        """
        try:
            from src.core.database.database import db_manager  # noqa: PLC0415
            from src.core.models.critique_models import CritiqueRecord  # noqa: PLC0415  # type: ignore[import-not-found]
            from src.core.utils.best_effort import best_effort  # noqa: PLC0415

            await db_manager.initialize()
            async with best_effort("critique_persist_to_db"):
                async with db_manager.get_session() as db:
                    row = CritiqueRecord(
                        critique_id=critique.critique_id,
                        agent_name=critique.agent_name,
                        task_id=critique.task_id,
                        tenant_id=critique.tenant_id,
                        score=max(0.0, min(1.0, critique.score)),
                        issues=critique.issues,
                        suggestions=critique.suggestions,
                        mode=critique.mode,
                        created_at=critique.timestamp,
                        metadata_json=critique.metadata if critique.metadata else None,
                    )
                    db.add(row)
                    await db.commit()
        except Exception as e:
            logger.error(
                "critique persist to postgres failed: %s: %s", type(e).__name__, e, exc_info=True
            )

    async def get_timeseries_stats(
        self, tenant_id: int, hours: int = 24
    ) -> list[CritiqueTimeseriesStats]:
        """Query critique_hourly_stats materialized view for hourly telemetry.

        Returns list of {hour, agent_name, avg_score, critique_count} dicts.
        Tenant-isolated via WHERE clause parameter binding.

        ignore: agents -> src.core.database.database (Cat B, SP-AGT-006, see .importlinter)
        """
        try:
            from src.core.database.database import db_manager  # noqa: PLC0415
            from sqlalchemy import text  # noqa: PLC0415

            cutoff = datetime.now(timezone.utc) - timedelta(hours=hours)
            await db_manager.initialize()
            async with db_manager.get_session() as db:
                result = await db.execute(
                    text(
                        "SELECT hour, agent_name, avg_score, critique_count"
                        " FROM critique_hourly_stats"
                        " WHERE tenant_id = :tenant_id AND hour >= :cutoff"
                        " ORDER BY hour DESC"
                    ),
                    {"tenant_id": tenant_id, "cutoff": cutoff},
                )
                rows = result.fetchall()
            return [
                {
                    "hour": row.hour.isoformat(),
                    "agent_name": row.agent_name,
                    "avg_score": float(row.avg_score),
                    "critique_count": row.critique_count,
                }
                for row in rows
            ]
        except Exception as e:
            logger.error(
                "critique timeseries query failed: %s: %s", type(e).__name__, e, exc_info=True
            )
            return []

    async def get_by_agent(
        self, tenant_id: int, agent_name: str, limit: int = 100
    ) -> list[Critique]:
        """
        Get critiques for a specific agent.

        Args:
            tenant_id: Tenant ID for isolation
            agent_name: Name of the agent
            limit: Maximum number of critiques to return

        Returns: List[Any] of critiques (newest first)  # TODO(TYPE): replace Any with concrete type
        """
        with self._lock:
            critiques = self._critiques_by_agent[tenant_id].get(agent_name, [])
            return sorted(critiques, key=lambda c: c.timestamp, reverse=True)[:limit]

    async def get_by_task(self, tenant_id: int, task_id: str) -> Critique | None:
        """Get critique for a specific task."""
        with self._lock:
            return self._critiques_by_task[tenant_id].get(task_id)

    async def get_average_score(
        self, tenant_id: int, agent_name: str | None = None, window_hours: int = 24
    ) -> float:
        """
        Get average score for an agent or all agents.

        Args:
            tenant_id: Tenant ID
            agent_name: Optional agent name filter
            window_hours: Time window in hours

        Returns:
            Average score (0.0 - 1.0)
        """
        with self._lock:
            from datetime import timedelta

            cutoff = datetime.now(timezone.utc) - timedelta(hours=window_hours)

            if agent_name:
                critiques = self._critiques_by_agent[tenant_id].get(agent_name, [])
            else:
                critiques = self._critiques[tenant_id]

            recent_critiques = [c for c in critiques if c.timestamp > cutoff]

            if not recent_critiques:
                return 0.0

            return sum(c.score for c in recent_critiques) / len(recent_critiques)

    async def get_score_distribution(
        self, tenant_id: int, agent_name: str, buckets: list[float] | None = None
    ) -> dict[str, int]:
        """
        Get score distribution for an agent.

        Args:
            tenant_id: Tenant ID
            agent_name: Agent name
            buckets: Score bucket boundaries (default: [0.3, 0.5, 0.7, 0.9])

        Returns: Dict[str, Any]ionary mapping bucket labels to counts  # TODO(TYPE): replace Any with concrete type
        """
        if buckets is None:
            buckets = [0.3, 0.5, 0.7, 0.9]

        with self._lock:
            critiques = self._critiques_by_agent[tenant_id].get(agent_name, [])

            distribution: dict[str, int] = defaultdict(int)

            for critique in critiques:
                score = critique.score
                if score < buckets[0]:
                    label = f"< {buckets[0]}"
                elif score < buckets[1]:
                    label = f"{buckets[0]}-{buckets[1]}"
                elif score < buckets[2]:
                    label = f"{buckets[1]}-{buckets[2]}"
                elif score < buckets[3]:
                    label = f"{buckets[2]}-{buckets[3]}"
                else:
                    label = f">= {buckets[3]}"

                distribution[label] += 1

            return dict(distribution)

    async def get_common_issues(
        self, tenant_id: int, agent_name: str, limit: int = 10
    ) -> list[tuple[str, int]]:
        """
        Get most common issues for an agent.

        Returns: List[Any] of (issue, count) tuples, sorted by count descending  # TODO(TYPE): replace Any with concrete type
        """
        with self._lock:
            critiques = self._critiques_by_agent[tenant_id].get(agent_name, [])

            issue_counts: dict[str, int] = defaultdict(int)
            for critique in critiques:
                for issue in critique.issues:
                    issue_counts[issue] += 1

            return sorted(issue_counts.items(), key=lambda x: x[1], reverse=True)[:limit]

    async def get_stats(
        self, tenant_id: int
    ) -> dict[str, Any]:  # TODO(TYPE): replace Any with concrete type
        """Get storage statistics for a tenant."""
        with self._lock:
            total_critiques = len(self._critiques[tenant_id])
            agent_counts = {
                agent: len(critiques)
                for agent, critiques in self._critiques_by_agent[tenant_id].items()
            }

            return {
                "total_critiques": total_critiques,
                "agents_tracked": len(agent_counts),
                "critiques_per_agent": agent_counts,
                "storage_limit": self._max_critiques_per_tenant,
            }

    async def clear_tenant(self, tenant_id: int) -> int:
        """Clear all critiques for a tenant. Returns number cleared."""
        with self._lock:
            count = len(self._critiques[tenant_id])

            del self._critiques[tenant_id]
            del self._critiques_by_agent[tenant_id]
            del self._critiques_by_task[tenant_id]

            logger.info(f"Cleared {count} critiques for tenant {tenant_id}")
            return count


# Global instance
critique_store = CritiqueStore()


def get_critique_store() -> CritiqueStore:
    """Get the global critique store instance."""
    return critique_store
